    public static int questionCount(int tier) { return tier <= 7 ? 5 : tier <= 14 ? 8 : 10; }
    public static int requiredCorrect(int tier) { return (questionCount(tier) * 80 + 99) / 100; }

    /** 试卷保存题目及选项快照，题库更新不影响正在进行的考试。 */
    public static List<Question> draw(int tier) {
        int group = tier <= 7 ? 0 : tier <= 14 ? 1 : 2;
        List<Integer> indices = new ArrayList<>();
        for (int i = 0; i < BANK.get(group).size(); i++) indices.add(i);
        Collections.shuffle(indices);
        List<Question> questions = new ArrayList<>();
        for (int index : indices.subList(0, questionCount(tier))) {
            Entry entry = BANK.get(group).get(index);
            List<String> options = new ArrayList<>(List.of(entry.correct(), entry.a(), entry.b(), entry.c()));
            Collections.shuffle(options);
            questions.add(new Question(group + "_" + index, entry.prompt(), List.copyOf(options), options.indexOf(entry.correct())));
        }
        return List.copyOf(questions);
    }
